"""Source of truth for the week scripts. Writes weeks/<id>.json. (w2 lives in its JSON.)"""
import json, pathlib
W = pathlib.Path(__file__).resolve().parents[1] / "weeks"


def T(week, title, speaker, org, photo, say, **kw):
    d = dict(type="title", say=say, eyebrow=f"Week {week} · " + kw.pop("kind", "Guest lecture"), title=title, speaker=speaker, org=org)
    if isinstance(photo, list):
        d["photos"] = photo
    elif photo:
        d["photo"] = photo
    d.update(kw)
    return d


def O(say, *lines, foot=None, footAt=5):
    d = dict(type="outro", say=say, lines=[dict(cue=c, text=t) for c, t in lines], footAt=footAt)
    if foot:
        d["foot"] = foot
    return d


